// --- Language Management ---
let currentLang = "en";

function detectLanguage() {
  // 1. URL parameter (?lang=ko)
  const urlLang = new URLSearchParams(window.location.search).get("lang");
  if (urlLang && TRANSLATIONS[urlLang]) return urlLang;

  // 2. localStorage
  const saved = localStorage.getItem("sudoku-lang");
  if (saved && TRANSLATIONS[saved]) return saved;

  // 3. Browser language
  const browserLang = navigator.language.slice(0, 2);
  if (TRANSLATIONS[browserLang]) return browserLang;

  return "en";
}

function setLanguage(lang) {
  if (!TRANSLATIONS[lang]) return;
  currentLang = lang;
  localStorage.setItem("sudoku-lang", lang);
  applyTranslations();
}

/**
 * Translation helper.
 * @param {string} key - Translation key
 * @param {...*} args - Values to replace {0}, {1}, etc.
 * @returns {string}
 */
function t(key, ...args) {
  let text =
    TRANSLATIONS[currentLang]?.[key] || TRANSLATIONS["en"]?.[key] || key;
  for (let i = 0; i < args.length; i++) {
    text = text.replaceAll(`{${i}}`, args[i]);
  }
  return text;
}

/**
 * Updates all DOM elements that have data-i18n* attributes.
 */
function applyTranslations() {
  // Text content
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  // Tooltips
  document.querySelectorAll("[data-i18n-tooltip]").forEach((el) => {
    el.dataset.tooltip = t(el.dataset.i18nTooltip);
  });
  // Placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  // Update HTML lang attribute
  document.documentElement.lang = currentLang;
  // Update language toggle button
  const langBtn = document.getElementById("lang-toggle");
  if (langBtn) {
    langBtn.textContent = currentLang === "ko" ? "EN" : "한";
  }
}

/**
 * Sets up the language switcher button.
 */
function setupLanguageSwitcher() {
  const btn = document.getElementById("lang-toggle");
  if (!btn) return;
  btn.addEventListener("click", async () => {
    btn.disabled = true;
    try {
      const newLang = currentLang === "en" ? "ko" : "en";
      setLanguage(newLang);
      // Refresh dynamically generated UI
      if (typeof updateButtonLabels === "function") updateButtonLabels();
      if (typeof updateSolverToggleButton === "function")
        updateSolverToggleButton();
      if (typeof updateControls === "function") updateControls();
      if (typeof renderPuzzleLevelLabel === "function")
        renderPuzzleLevelLabel();
      if (typeof populateSelectors === "function") {
        const ds = document.getElementById("date-select");
        const ls = document.getElementById("level-select");
        const oldDateVal = ds ? ds.value : null;
        const oldLevelVal = ls ? ls.value : null;
        populateSelectors();
        if (ds && oldDateVal) ds.value = oldDateVal;
        if (ls && oldLevelVal) ls.value = oldLevelVal;
      }

      if (
        typeof isSolverMode !== "undefined" &&
        isSolverMode &&
        typeof refreshSolverAfterLanguageChange === "function"
      ) {
        await refreshSolverAfterLanguageChange();
      } else if (typeof onBoardUpdated === "function") {
        onBoardUpdated();
      }
    } finally {
      btn.disabled = false;
    }
  });
}
